// Regenerate src/content/situations/meta.gen.ts: each conversation's light fields (types.ts SITUATION_META_FIELDS) and the
// loader of its file, which the bundler makes a chunk of its own (docs: catalog.ts). Run after gen-index.ts, and after
// changing a conversation's title, goal, intro, place, people, song, chapter or order (tests/situation-meta.test.ts
// says when it is out of step).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SITUATION_META_FIELDS as META_FIELDS, type SituationDef } from "../src/content/types";

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/content/situations");
const files = fs.readdirSync(dir).filter((f) => /^[spx]\d\d[a-z]?-.+\.ts$/.test(f)).sort();
const rows: string[] = [], loads: string[] = [];
for (const f of files) {
  const mod = f.replace(/\.ts$/, "");
  const def: SituationDef = (await import(path.join(dir, f))).default;
  const meta: Record<string, unknown> = {};
  for (const k of META_FIELDS) if ((def as any)[k] !== undefined) meta[k] = (def as any)[k];
  rows.push("  " + JSON.stringify(meta) + ",");
  loads.push(`  ${JSON.stringify(def.id)}: () => import("./${mod}").then((m) => m.default),`);
}
const out = `// Generated by tools/gen-meta.ts: what the game knows of each conversation before its file is loaded (catalog.ts).
import type { SituationDef, SituationMeta } from "../types";

export const META: SituationMeta[] = [
${rows.join("\n")}
];

export const LOAD: Record<string, () => Promise<SituationDef>> = {
${loads.join("\n")}
};
`;
fs.writeFileSync(path.join(dir, "meta.gen.ts"), out);
console.log(`meta.gen.ts: ${files.length} situations`);
