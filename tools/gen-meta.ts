// Regenerate a conversation catalogue's meta.gen.ts (src/content/situations/catalog.ts): each conversation's light
// fields (types.ts SITUATION_META_FIELDS) and the loader of its file, which the bundler makes a chunk of its own.
// Run after gen-index.ts and after changing a conversation's title, goal, intro, place, people, song, chapter or order
// (tests/situation-meta.test.ts and its es / es-lt twins say when one is out of step), for each edition and layer:
//   npx tsx tools/gen-meta.ts                                                   # Maple Harbor
//   EDITION=es npx tsx --import ./tools/edition-hook.mjs tools/gen-meta.ts                # Puerto Colibrí
//   EDITION=es LEARNER=lt npx tsx --import ./tools/edition-hook.mjs tools/gen-meta.ts     # … for Lithuanians
// The learner's layer has no conversation files of its own: its loaders are the edition's, with the layer's table put
// in (as its index.ts does to all of them at once), and its light fields are the ones the learner reads.
import fs from "node:fs";
import path from "node:path";
import { EDITION } from "../src/edition";
import { SITUATIONS } from "../src/content/situations";
import { SITUATION_META_FIELDS as META_FIELDS, type SituationDef } from "../src/content/types";

const learner = process.env.LEARNER || process.env.VITE_LEARNER || "";
const sitDir = path.resolve(EDITION.contentDir, "situations");
const outDir = learner ? path.resolve("src/editions", `${EDITION.id}-${learner}`, "content/situations") : sitDir;
const files = fs.readdirSync(sitDir).filter((f) => /^[spx]\d\d[a-z]?-.+\.ts$/.test(f)).sort();
const byId = new Map(SITUATIONS.map((s) => [s.id, s]));
const rows: string[] = [], loads: string[] = [];
for (const f of files) {
  const mod = f.replace(/\.ts$/, "");
  const file: SituationDef = (await import(path.join(sitDir, f))).default;
  const def = byId.get(file.id);
  if (!def) throw new Error(`${f}: ${file.id} is not in the index (run gen-index.ts)`);
  const meta: Record<string, unknown> = {};
  for (const k of META_FIELDS) if ((def as any)[k] !== undefined) meta[k] = (def as any)[k];
  rows.push("  " + JSON.stringify(meta) + ",");
  loads.push(`  ${JSON.stringify(def.id)}: () => import("./${mod}").then((m) => m.default),`);
}
const types = EDITION.id === "en" ? "../types" : "@/content/types";
const head = `// Generated by tools/gen-meta.ts: what the game knows of each conversation before its file is loaded (catalog.ts).`;
const meta = `export const META: SituationMeta[] = [\n${rows.join("\n")}\n];\n`;
const tablesDir = path.resolve("src/editions", `${EDITION.id}-${learner}`, "tables");
const out = learner
  ? `${head}
// The ${EDITION.id} edition's conversations for this learner: their fields in the learner's language, and each file with
// the learner's table put in when it loads (as index.ts does to all of them at start): the conversation's own table
// (tables/<id>.json) and, with the first one, every table's texts (tables/value-text.gen.json; tables/loaded.ts).
import type { SituationDef, SituationMeta } from "${types}";
import { LOAD as EDITION_LOAD } from "@/content/situations/meta.gen";
import { applyLearner, type LearnerTable } from "../../../${EDITION.id}/learner/walk";
import { LOADED, learnerApplied, loadValueText } from "../../tables/loaded";

${meta}
const TABLE: Record<string, () => Promise<{ default: unknown }>> = {
${[...byId.keys()].filter((id) => fs.existsSync(path.join(tablesDir, id + ".json"))).map((id) => `  ${JSON.stringify(id)}: () => import("../../tables/${id}.json"),`).join("\n")}
};

export const LOAD: Record<string, () => Promise<SituationDef>> = Object.fromEntries(Object.entries(EDITION_LOAD).map(([id, load]) =>
  [id, () => Promise.all([load(), TABLE[id]?.(), loadValueText()]).then(([def, t]) => {
    const table = (t?.default ?? LOADED[id]) as LearnerTable | undefined;
    if (table) LOADED[id] = table;
    // (once: a conversation loaded again after a failed fetch is the same object)
    if (table && !learnerApplied.has(def)) { applyLearner(def, table); learnerApplied.add(def); }
    return def;
  })]));
`
  : `${head}
import type { SituationDef, SituationMeta } from "${types}";

${meta}
export const LOAD: Record<string, () => Promise<SituationDef>> = {
${loads.join("\n")}
};
`;
if (learner) {
  // every table's texts by their English, in the order the tables have (tables/loaded.ts mergeValueText)
  const { TABLES } = await import(path.join(tablesDir, "tables.gen.ts"));
  const { mergeValueText } = await import(path.join(tablesDir, "loaded.ts"));
  fs.writeFileSync(path.join(tablesDir, "value-text.gen.json"), JSON.stringify(Object.fromEntries(mergeValueText(TABLES))) + "\n");
}
fs.writeFileSync(path.join(outDir, "meta.gen.ts"), out);
console.log(`${path.relative(process.cwd(), outDir)}/meta.gen.ts: ${files.length} situations`);
